"""``reports/phase1_flood_definition.md`` — the Doc 04 §8 deliverable.

Doc 04 §8 asks for *"the rule, plus measured precision and recall"*, and Doc 04
§4.2 says both numbers go in the paper. This module writes that report from the
pipeline as it actually stands, so every number in it is recomputed rather than
transcribed.

The report has five parts:

1. **The rule** — the six steps of Doc 02 §3.1 with the config values in force.
2. **What the rule produced** — counts, rates, severity split, threshold spread.
3. **Sensitivity (Doc 02 §3.5)** — Q5 for Q2, 5-day for 3-day declustering,
   250 km² for 50 km² eligibility, each re-run end to end.
4. **The blind spot (Doc 02 §3.4)** — the claim that GloFAS cannot see the
   Punnapuzha at Chooralmala, checked against the network we built.
5. **Corroboration (Doc 02 §3.3)** — precision and recall, each with an explicit
   status. Where a number cannot be computed the report says so and says what
   unblocks it. It never guesses.
"""

from __future__ import annotations

from datetime import date

import numpy as np
import pandas as pd

from .. import paths
from ..config import Node
from ..logging_setup import get

log = get("qa.flood_definition")

REPORT_PATH = paths.REPORTS / "phase1_flood_definition.md"


def _fmt(x: float, nd: int = 2) -> str:
    return "—" if x is None or not np.isfinite(x) else f"{x:,.{nd}f}"


def build(cfg: Node, *, write: bool = True) -> str:
    from ..ingest import adapters, corroboration, floods
    from ..spatial.network import Network

    net = Network()
    reaches = net.gdf[["reach_id", "area_dn_km2"]].copy()
    areas = reaches.set_index("reach_id")["area_dn_km2"]

    log.info("building the discharge table once and reusing it for every variant")
    disch = adapters.discharge(cfg, reaches)
    synthetic = bool(disch.attrs.get("synthetic", False))

    events = floods.detect_for_all_reaches(disch, areas, cfg)
    start, end = str(cfg.period.start), str(cfg.period.end)
    in_period = events[(events["date"] >= start) & (events["date"] <= end)]

    sens = corroboration.sensitivity(cfg, disch, areas)
    try:
        blind = corroboration.blind_spot(cfg)
    except FileNotFoundError as exc:
        log.warning("blind-spot check skipped: %s", exc)
        blind = None

    reference = corroboration.ensure_reference_list(cfg)
    rec = corroboration.recall(in_period.rename(columns={"date": "date"}),
                               reference, synthetic=synthetic)

    try:
        corroboration.sentinel1_precision(cfg, in_period)
        precision_note = "unexpectedly returned; wire the result in here"
    except Exception as exc:  # noqa: BLE001 — the message *is* the deliverable
        precision_note = str(exc)

    text = _render(cfg, net, areas, disch, events, in_period, sens, blind,
                   rec, precision_note, synthetic)
    if write:
        paths.REPORTS.mkdir(parents=True, exist_ok=True)
        REPORT_PATH.write_text(text, encoding="utf-8")
        log.info("wrote   reports/%s", REPORT_PATH.name)
    return text


# ------------------------------------------------------------------ render ---

def _render(cfg, net, areas, disch, events, in_period, sens, blind, rec,
            precision_note, synthetic) -> str:
    from ..ingest.floods import expected_exceedance_rate

    f = cfg.floods
    rp = int(f.threshold_return_period)
    dc = int(f.decluster_days)
    min_area = float(f.min_contributing_area_km2)
    n_elig = int((areas > min_area).sum())

    L: list[str] = []
    A = L.append

    A("# Phase 1 — the flood definition, and how well it holds up")
    A("")
    A(f"*Generated by `hydrocascade report` on {date.today().isoformat()}. "
      f"Every number below is recomputed from the pipeline; nothing is transcribed.*")
    A("")
    A(f"Region `{cfg.region.id}` · period {cfg.period.start} to {cfg.period.end} "
      f"· {len(net):,} reaches · analysis CRS {cfg.crs.analysis}")
    A("")

    if synthetic:
        A("> ### ⚠ The discharge is synthetic")
        A(">")
        A("> `data_mode.glofas` is `synthetic`, so the numbers in sections 2, 3 and 5")
        A("> describe a stand-in generator, not the GloFAS reanalysis. They are here to")
        A("> show that the procedure runs end to end and that the diagnostics fire; they")
        A("> are **not results and must not be quoted**. Sections 1 and 4 are independent")
        A("> of the discharge source and stand as they are.")
        A(">")
        A("> Putting GloFAS files in `data/raw/GLOFAS/<date>/` (or supplying a CDS key)")
        A("> and setting `data_mode.glofas: real` turns every one of them into a")
        A("> result. `docs/15_HOW_TO_RUN.md` section 3.2 has the exact steps.")
        A("")

    # ---------------------------------------------------------- 1. the rule ---
    A("## 1. The rule")
    A("")
    A("Doc 02 §3.1, implemented in `src/hydrocascade/ingest/floods.py`. It is a "
      "procedure with no judgement calls in it, which is the point: four people "
      "running it get the same catalog.")
    A("")
    A("| Step | What happens | Config key | Value in force |")
    A("|---|---|---|---|")
    A(f"| 1 | Annual maxima of daily discharge per reach | `period` | full record "
      f"{disch.index.min().date()} to {disch.index.max().date()} |")
    A(f"| 2 | Fit **Gumbel by L-moments**, read Q2, Q5, Q20 | `floods.return_periods` "
      f"| {list(f.return_periods)} |")
    A(f"| 3 | An event opens on the first day Q exceeds the threshold | "
      f"`floods.threshold_return_period` | Q{rp} |")
    A(f"| 4 | The episode closes after N consecutive days below it | "
      f"`floods.decluster_days` | {dc} days |")
    A(f"| 5 | Only reaches above the eligibility area are detected on | "
      f"`floods.min_contributing_area_km2` | {min_area:.0f} km² |")
    A(f"| 6 | Mark `m_F = log(Q_peak / Q2)`; class from the Q2/Q5/Q20 bands | — | — |")
    A("")
    A("**Why L-moments and not maximum likelihood.** A record containing 2018 and "
      "2024 has two enormous annual maxima. Maximum likelihood lets them drag the "
      "fitted scale; L-moments are built from order statistics and barely move. "
      "This is also GloFAS's own threshold procedure, so adopting it means our "
      "flood definition matches an operational system instead of being invented "
      "for this project.")
    A("")
    A("**Why declustering is not optional.** Without it a single week-long flood "
      "counts as five events at the same reach, which inflates exactly the "
      "self-excitation the model is supposed to measure. Three sub-threshold days "
      "is the Doc 02 §3.1 step 3 rule.")
    A("")
    A(f"**Eligibility.** {n_elig:,} of {len(areas):,} reaches clear {min_area:.0f} km². "
      f"Operational GloFAS reporting points are restricted to catchments above "
      f"250 km²; {min_area:.0f} km² is the research-mode compromise Doc 02 §3.1 "
      f"step 5 allows, and §3 requires the 250 km² check that section 3 below runs.")
    A("")

    # --------------------------------------------------- 2. what it produced ---
    A("## 2. What the rule produced")
    A("")
    n_ev = len(in_period)
    if n_ev:
        yrs = pd.to_datetime(in_period["date"]).dt.year
        span = max(int(yrs.max()) - int(yrs.min()) + 1, 1)
        n_r = int(in_period["reach_id"].nunique())
        sev = in_period["severity_class"].value_counts()
        rate = n_ev / n_r / span
        expected = expected_exceedance_rate(rp)
        # one threshold per reach, not one per event, or the median is weighted
        # by how often each reach happened to flood
        q2_by_reach = in_period.groupby("reach_id")["q2"].first()
        A("| Quantity | Value |")
        A("|---|---|")
        A(f"| flood events in the study period | **{n_ev:,}** |")
        A(f"| reaches with at least one event | {n_r:,} of {n_elig:,} eligible |")
        A(f"| exceedance rate | {rate:.2f} events per reach-year "
          f"(Q{rp} implies {expected:.2f}) |")
        A(f"| median days above threshold per event | {in_period['n_days_above'].median():.0f} |")
        A(f"| severity split | {int(sev.get('minor', 0)):,} minor · "
          f"{int(sev.get('major', 0)):,} major · {int(sev.get('extreme', 0)):,} extreme |")
        A(f"| Q2 per reach (reaches with events) | median {q2_by_reach.median():,.1f} m³/s, "
          f"range {q2_by_reach.min():,.1f}–{q2_by_reach.max():,.1f} |")
        A(f"| events outside the study period (threshold-fitting record only) | "
          f"{len(events) - n_ev:,} |")
        A("")
        A(f"**The rate is the diagnostic to read first**, because it is fixed by the "
          f"return period alone. If episodes above Q{rp} arrive as a Poisson process "
          f"with rate λ, the annual maximum stays below Q{rp} with probability "
          f"`exp(−λ)`, and the return period pins that at `1 − 1/{rp}` — so "
          f"λ = −ln(1 − 1/{rp}) = **{expected:.2f}** events per reach-year, not 1.0. "
          f"This run gives **{rate:.2f}**, a ratio of {rate / expected:.2f}. A rate far "
          f"from the theoretical one indicts the discharge series, not the detection "
          f"rule, and `floods.detect_for_all_reaches` warns when the ratio leaves "
          f"0.4–2.5.")
        A("")
        by_year = in_period.assign(year=yrs).groupby("year").size()
        A("**Events per year**")
        A("")
        A("| year | " + " | ".join(str(y) for y in by_year.index) + " |")
        A("|---" * (len(by_year) + 1) + "|")
        A("| events | " + " | ".join(f"{v:,}" for v in by_year.values) + " |")
        A("")
    else:
        A("No events were detected in the study period. That is itself a finding: "
          "check the discharge table before touching the thresholds.")
        A("")

    # -------------------------------------------------------- 3. sensitivity ---
    A("## 3. Sensitivity — Doc 02 §3.5")
    A("")
    A("Each variant re-runs the whole procedure on the same discharge table. "
      "Doc 11 §5 rule 3 says a variant is a config edit, not a code edit, so "
      "`corroboration.sensitivity` builds a modified config and calls the same "
      "detector the headline run uses — there is no second implementation to "
      "drift out of sync.")
    A("")
    A("| Variant | Eligible reaches | Events | Reaches hit | Rate /reach-yr | "
      "minor / major / extreme |")
    A("|---|---|---|---|---|---|")
    for _, r in sens.iterrows():
        A(f"| {r['label']} | {int(r['n_eligible_reaches']):,} | "
          f"**{int(r['n_events']):,}** | {int(r['n_reaches_with_events']):,} | "
          f"{_fmt(r['rate_per_reach_year'])} | "
          f"{int(r['n_minor']):,} / {int(r['n_major']):,} / {int(r['n_extreme']):,} |")
    A("")
    base = sens.iloc[0]
    for _, r in sens.iloc[1:].iterrows():
        if base["n_events"]:
            delta = 100.0 * (r["n_events"] - base["n_events"]) / base["n_events"]
            A(f"- **{r['label']}**: {int(r['n_events']):,} events, "
              f"{delta:+.0f}% against the headline.")
    A("")
    A("Two things in that table look like bugs and are not.")
    A("")
    A("- **The Q5 row has no `minor` events.** `severity_class` is defined by the "
      "Q2/Q5/Q20 bands (Doc 02 §3.1 step 4) and `minor` means Q2–Q5. Detecting at "
      "Q5 means every event is at least Q5 by construction, so the `minor` bin is "
      "necessarily empty. The severity scale stays anchored to Q2 even when the "
      "detection threshold moves, which is what keeps marks comparable across "
      "variants.")
    A("- **Each variant's rate is close to its own theoretical value, not to the "
      "others.** Q2 implies "
      f"{expected_exceedance_rate(2):.2f} events per reach-year and Q5 implies "
      f"{expected_exceedance_rate(5):.2f}. A variant whose rate tracked the "
      "headline's instead would be the thing to worry about.")
    A("")
    A("Doc 02 §3.5 asks whether the *sign and significance of the cross-hazard "
      "coupling* change under these variants. That question cannot be answered "
      "until the coupling is fitted in Phase 4. What Phase 1 owes is the "
      "machinery and the event counts, which is what this table is; the Phase 5 "
      "ablation reruns the fit on each variant catalog.")
    A("")

    # --------------------------------------------------------- 4. blind spot ---
    A("## 4. The blind spot — Doc 02 §3.4, checked rather than repeated")
    A("")
    A("Doc 02 §3.4 states up front that the Punnapuzha at Chooralmala has a "
      "contributing area *far below* the eligibility threshold, so the discharge "
      "rule cannot see the flood at the debris-flow site. We now have the "
      "catchment, so the claim can be verified instead of restated.")
    A("")
    if blind is None:
        A("*Not evaluated: the Phase 2 spatial framework is not built. "
          "Run `hydrocascade traveltime` first.*")
    else:
        A("| | reach | catchment | eligible at "
          f"{min_area:.0f} km²? |")
        A("|---|---|---|---|")
        A(f"| Mundakkai injection point | `R-{blind['injection_reach']:05d}` | "
          f"{blind['injection_area_km2']:.1f} km² | "
          f"**no** |")
        A(f"| Punnapuzha at the Chooralmala bridge | `R-{blind['chooralmala_reach']:05d}` | "
          f"{blind['chooralmala_area_km2']:.1f} km² | "
          f"**{'yes' if blind['chooralmala_area_km2'] > min_area else 'no'}** |")
        A("")
        ca = max(blind["chooralmala_area_km2"], 1e-9)
        A(f"The bridge landmark snaps to its reach at "
          f"{blind['chooralmala_snap_dist_m']:.0f} m. **Doc 02 §3.4 is confirmed at "
          f"both thresholds**, though the margin is worth stating precisely rather "
          f"than repeating the word *far*: the Punnapuzha here drains "
          f"{blind['chooralmala_area_km2']:.1f} km², which is "
          f"{min_area / ca:.1f}× below our research-mode {min_area:.0f} km² bar and "
          f"{250.0 / ca:.0f}× below the 250 km² bar operational GloFAS reporting "
          f"points actually use. The injection point itself, at "
          f"{blind['injection_area_km2']:.1f} km², is not close to either.")
        A("")
        A("**Where the rule regains sight.** Following the chain downstream from "
          "the injection point:")
        A("")
        A("| eligibility | first visible reach | its catchment | reaches blind before it | "
          "travel time from the injection point |")
        A("|---|---|---|---|---|")
        for thr, d in blind["thresholds"].items():
            if d["visible"]:
                A(f"| {thr:.0f} km² | `R-{d['first_reach']:05d}` | "
                  f"{d['first_area_km2']:.0f} km² | {d['reaches_blind']} | "
                  f"{d['hours_from_injection']:.1f} h |")
            else:
                A(f"| {thr:.0f} km² | none | — | all {d['reaches_blind']} | — |")
        A("")
        A("This is the quantitative form of the limitation, and it belongs in the "
          "paper exactly like this. For the Wayanad backtest the model's predicted "
          "intensity at the headwater reaches can be validated only qualitatively — "
          "did risk rise in the right place at the right time — and quantitatively "
          "only from the first eligible reach downstream. Hiding that would be the "
          "fastest way to lose a reviewer.")
    A("")

    # ------------------------------------------------------ 5. corroboration ---
    A("## 5. Corroboration — Doc 02 §3.3")
    A("")
    A("The definition is model-derived, so Doc 02 §3.3 requires it to be scored "
      "against observations. Two numbers, two statuses.")
    A("")
    A("### 5.1 Precision — Sentinel-1 inundation *(FR-05)*")
    A("")
    A("*Of the events the rule flags, what fraction show a real inundation signal?*")
    A("")
    A("Doc 11 FR-05 names this report as the place the number is reported and an "
      "automated check as its verification. **Status: BLOCKED** — not estimated, "
      "not approximated, not filled in with a plausible figure. FR-05 is "
      "therefore recorded as unmet, which is a truthful state for a requirement "
      "to be in.")
    A("")
    A("```")
    A(precision_note.rstrip())
    A("```")
    A("")
    A("### 5.2 Recall — independently documented floods")
    A("")
    A("*Of the floods that are independently documented, what fraction did the "
      "rule flag?*")
    A("")
    status_word = {"measured": "MEASURED", "exercise": "HARNESS EXERCISE",
                   "blocked": "BLOCKED"}[rec.status]
    A(f"**Status: {status_word}.**")
    A("")
    if rec.status == "blocked":
        A(rec.reason)
    else:
        A(f"| | |")
        A(f"|---|---|")
        A(f"| reference rows | {rec.n_reference} |")
        A(f"| carrying a source URL (FR-04) | {rec.n_sourced} |")
        A(f"| scorable (not marked outside the pilot basin) | {rec.n_scored} |")
        A(f"| matched within ±{rec.window_days} days | {rec.n_matched} |")
        A(f"| **recall** | **{100 * rec.value:.0f}%** |")
        A("")
        if rec.reason:
            A(f"> **{rec.reason}**")
            A("")
        A("A reference flood counts as detected when **any** reach in the basin "
          "recorded an event within the window. That is deliberately basin-scale: "
          "published accounts name a town, not a reach, and inventing a reach id "
          "for them would be worse than measuring a coarser quantity honestly.")
        A("")
        cols = ["flood_id", "date_start", "date_end", "place", "district",
                "in_pilot_basin", "matched", "nearest_detection", "evidence_type"]
        show = rec.detail[cols]
        A("| " + " | ".join(cols) + " |")
        A("|" + "---|" * len(cols))
        for _, r in show.iterrows():
            A("| " + " | ".join(
                ("✓" if r[c] is True else "✗" if r[c] is False else str(r[c]) or "—")
                for c in cols) + " |")
        A("")
    A(f"The list lives in `data/reference/documented_floods.csv`. It is scored "
      f"against, never fitted to. Rows without a `source_url` are ignored on the "
      f"same FR-04 rule the catalog uses — a row nobody can trace is not evidence.")
    A("")

    # --------------------------------------------------------- what is next ---
    A("## 6. What turns this into the paper's version")
    A("")
    A("| Blocker | Unblocked by | Turns into |")
    A("|---|---|---|")
    A("| synthetic discharge | a free Copernicus CDS account and `data_mode.glofas: real` "
      "| every count in §2, §3 and §5.2 |")
    A("| no SAR precision | a Google Earth Engine account and `data_mode.sentinel1: real` "
      "| §5.1 |")
    A("| reference list sourced to the project brief | one afternoon in the KSDMA "
      "annual reports, the Copernicus EMS activation list and the CWC portal, one "
      "`source_url` per row | a publishable §5.2 |")
    A("")
    A("None of the three needs a code change. That was the design intent of "
      "`ingest/adapters.py`: the pipeline never blocks on an approval email, and "
      "it never quietly reports the stand-in as though it were the real thing.")
    A("")
    return "\n".join(L)
